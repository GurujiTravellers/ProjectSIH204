function locationMatches(trainCity, trainStation, loc) {
  if (!trainCity || !loc) return false;
  const tc = String(trainCity).toLowerCase().replace(/[^a-z]/g, "");
  const lid = String(loc.id || "").toLowerCase().replace(/[^a-z]/g, "");
  const lname = String(loc.name || "").toLowerCase().replace(/[^a-z]/g, "");

  // 1. Exact city name or ID match
  if (tc === lid || tc === lname) return true;

  // 2. Specific station code match inside parentheses e.g. (HWH), (SDAH), (PURI), (CSMT), (NDLS), (MAO), (ASR), (ADI), (VSKP)
  if (loc.stations && trainStation) {
    for (const s of loc.stations) {
      if (trainStation.includes(`(${s.code})`) || trainStation.includes(` ${s.code} `) || trainStation.endsWith(` ${s.code}`)) {
        return true;
      }
    }
  }

  // 3. Exact alias match against trainCity
  if (loc.aliases) {
    for (const a of loc.aliases) {
      if (a.toLowerCase().replace(/[^a-z]/g, "") === tc) return true;
    }
  }

  // 4. Station name match against location aliases (for multi-city stations e.g. Madgaon in Goa)
  if (loc.aliases && trainStation) {
    const tsLower = trainStation.toLowerCase();
    for (const a of loc.aliases) {
      if (a.length > 3 && tsLower.includes(a.toLowerCase())) return true;
    }
  }

  // 5. Cross-state alias matching (e.g. Punjab <-> Amritsar, Gujarat <-> Ahmedabad, Vizag <-> Visakhapatnam)
  if (
    (tc === "amritsar" && (lid === "punjab" || lname.toLowerCase() === "punjab")) ||
    (tc === "punjab" && (lid === "amritsar" || lname.toLowerCase() === "amritsar")) ||
    (tc === "ahmedabad" && (lid === "gujarat" || lname.toLowerCase() === "gujarat")) ||
    (tc === "gujarat" && (lid === "ahmedabad" || lname.toLowerCase() === "ahmedabad")) ||
    (tc === "vizag" && (lid === "visakhapatnam" || lname.toLowerCase() === "visakhapatnam")) ||
    (tc === "visakhapatnam" && (lid === "vizag" || lname.toLowerCase() === "vizag"))
  ) {
    return true;
  }

  return false;
}

/**
 * Filter trains by matching city / stations and optionally by day of week
 */
function findAuthenticTrains(originLoc, destLoc, travelDate = "") {
  if (!originLoc || !destLoc) return [];

  // Determine day of week accurately
  let dayOfWeek = "";
  if (travelDate) {
    try {
      const parts = String(travelDate).split("-");
      if (parts.length === 3) {
        const y = parseInt(parts[0], 10);
        const m = parseInt(parts[1], 10) - 1;
        const d = parseInt(parts[2], 10);
        const dateObj = new Date(y, m, d);
        dayOfWeek = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"][dateObj.getDay()];
      }
    } catch {
      // ignore
    }
  }

  // 1. First find all trains matching origin and destination
  const matchedTrains = ALL_AUTHENTIC_TRAINS.filter((t) => {
    const oMatch = locationMatches(t.originCity, t.originStation, originLoc);
    const dMatch = locationMatches(t.destCity, t.destStation, destLoc);
    return oMatch && dMatch;
  });

  if (matchedTrains.length === 0) return [];

  // 2. Filter by day of week if requested
  if (dayOfWeek) {
    const dayFiltered = matchedTrains.filter((t) => {
      if (!t.runningDays || t.runningDays.includes("Daily")) return true;
      return t.runningDays.includes(dayOfWeek);
    });

    if (dayFiltered.length > 0) {
      return dayFiltered;
    }

    // If trains exist on this corridor but not on this specific day of week,
    // return them with clear schedule notice so user sees available trains for the route!
    return matchedTrains.map((t) => ({
      ...t,
      availabilityStatus: `Runs on ${t.runningDays?.join(", ") || "Weekly"} | Next departure on IRCTC ↗`,
      scheduleNotice: `This train operates on ${t.runningDays?.join(", ") || "Weekly"}. Selected date is ${dayOfWeek}. Verify next departure on IRCTC.`,
    }));
  }

  return matchedTrains;
}

