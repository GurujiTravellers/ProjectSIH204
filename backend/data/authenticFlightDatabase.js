const { NATIONAL_FLIGHTS } = require("./authenticNationalFlights");
const ALL_AUTHENTIC_FLIGHTS = [...AUTHENTIC_FLIGHTS, ...(NATIONAL_FLIGHTS || [])];

function flightLocationMatches(flightCity, flightCode, flightAirport, loc) {
  if (!loc) return false;
  const fc = String(flightCity || "").toLowerCase().replace(/[^a-z]/g, "");
  const lid = String(loc.id || "").toLowerCase().replace(/[^a-z]/g, "");
  const lname = String(loc.name || "").toLowerCase().replace(/[^a-z]/g, "");

  // 1. Direct city or ID match
  if (fc === lid || fc === lname) return true;

  // 2. Direct IATA airport code match e.g. CCU, DEL, BOM, BLR, MAA, IXB, IXC, GOI, GOX, VNS, SXR
  if (flightCode && loc.airports) {
    if (loc.airports.some((a) => a.code.toUpperCase() === String(flightCode).toUpperCase())) {
      return true;
    }
  }

  // 3. Nearest commercial air hub match (e.g. BBI for Puri, IXB for Darjeeling, IXC for Shimla)
  if (flightCode && loc.nearestAirHub && loc.nearestAirHub.airportCode) {
    if (loc.nearestAirHub.airportCode.toUpperCase() === String(flightCode).toUpperCase()) {
      return true;
    }
  }

  // 4. Aliases matching
  if (loc.aliases) {
    for (const a of loc.aliases) {
      if (a.toLowerCase().replace(/[^a-z]/g, "") === fc) return true;
    }
  }

  return false;
}

/**
 * Filter authentic flights by matching origin/dest locations
 */
function findAuthenticFlights(originLoc, destLoc) {
  if (!originLoc || !destLoc) return [];

  return ALL_AUTHENTIC_FLIGHTS.filter((f) => {
    const oMatch = flightLocationMatches(f.originCity, f.originCode, f.originAirport, originLoc);
    const dMatch = flightLocationMatches(f.destCity, f.destCode, f.destAirport, destLoc);
    return oMatch && dMatch;
  });
}

module.exports = {
  AUTHENTIC_FLIGHTS: ALL_AUTHENTIC_FLIGHTS,
  findAuthenticFlights,
};

